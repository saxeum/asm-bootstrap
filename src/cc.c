/* src/cc.c -- the compiler, written in the subset it compiles.
 *
 * Slice 1: emitstr, emitc, putn, line -- the output side, and one program
 *          emitted line by line.
 * Slice 2: the prologue and epilogue emitted from tables of literal addresses.
 * Slice 3: a complete program with a *literal section* -- the text, the quoted
 *          bytes, the end label and the terminating zero -- which is the shape
 *          `cc` itself emits for helloworld.c. The output runs: it prints
 *          "Hello, World!".
 *
 * Judged by two things, because one is not enough:
 *
 *     ./.work/cc1 | cmp - tests/selfhost/slice3.expected      bytes
 *     ./.work/cc1 > prog.s ; asm1 < prog.s > prog ; ./prog      behaviour
 *
 * Both expected artefacts were written before this slice. Not here yet: the
 * front end (a scanner, the symbol table, statements, expressions).
 *
 * Workarounds this file lives with (docs/cc.md): the loop stays in the caller,
 * because a pointer subscript is char-indexed and an int array cannot cross a
 * call; no `&&`; `\n` is 10.
 */

/* the characters of s, at position len; return the new length */
int emitstr(int p, int len, int s)
{
	int i = 0;
	while (s[i] != 0) {
		p[len] = s[i];
		len = len + 1;
		i = i + 1;
	}
	return len;
}

/* one character */
int emitc(int p, int len, int c)
{
	p[len] = c;
	return len + 1;
}

/* a decimal number 0..65535, no leading zeros; return the new length */
int putn(int p, int len, int n)
{
	int place = 10000;
	int started = 0;
	int d = 0;
	while (place > 0) {
		d = (n / place) - ((n / place) / 10) * 10;
		if (d > 0) { started = 1; }
		if (started == 1) {
			p[len] = '0' + d;
			len = len + 1;
		}
		place = place / 10;
	}
	if (started == 0) { p[len] = '0'; len = len + 1; }
	return len;
}

/* one line of text, then a newline */
int line(int p, int len, int s)
{
	len = emitstr(p, len, s);
	len = emitc(p, len, 10);
	return len;
}

/* one literal section entry: m<k>: / db "<text>" / m<k>end: / db 0 */
int lit(int p, int len, int k, int s)
{
	len = emitc(p, len, 'm');
	len = putn(p, len, k);
	len = emitc(p, len, ':');
	len = emitc(p, len, 10);
	len = emitstr(p, len, "db ");
	len = emitc(p, len, 34);
	len = emitstr(p, len, s);
	len = emitc(p, len, 92);  /* backslash: the dialect escape, written out */
	len = emitc(p, len, 110); /* n: so the literal ends with a newline */
	len = emitc(p, len, 34);
	len = emitc(p, len, 10);
	len = emitc(p, len, 'm');
	len = putn(p, len, k);
	len = emitstr(p, len, "end:");
	len = emitc(p, len, 10);
	len = emitstr(p, len, "db 0");
	len = emitc(p, len, 10);
	return len;
}

int main(void)
{
	char obuf[8000];
	int pro[15];
	int p = &obuf;
	int len = 0;
	pro[0] = "; generated by cc: dialect source, not a program. Assemble it with asm1";
	pro[1] = "main:";
	pro[2] = "push rbp";
	pro[3] = "mov rbp, rsp";
	pro[4] = "mov rcx, 16500";
	pro[5] = "sub rsp, rcx";
	pro[6] = "mov eax, 1";
	pro[7] = "mov edi, 1";
	pro[8] = "mov esi, 4194424+m1";
	pro[9] = "mov edx, m1end-m1";
	pro[10] = "syscall";
	pro[11] = "mov rax, 0";
	pro[12] = "mov rdi, rax";
	pro[13] = "mov eax, 60";
	pro[14] = "syscall";
	int i = 0;
	while (i < 15) {
		len = line(p, len, pro[i]);
		i = i + 1;
	}
	len = line(p, len, "entry main");
	len = lit(p, len, 1, "Hello, World!");
	int k = write(obuf, len);
	return 0;
}
